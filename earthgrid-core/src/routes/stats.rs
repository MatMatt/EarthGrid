#[derive(Deserialize)]
pub struct CoverageQuery {
    pub source: Option<String>,
}

pub(crate) async fn coverage_spatial(
    State(state): State<AppState>,
    Query(q): Query<CoverageQuery>,
) -> impl IntoResponse {
    let force_local = q.source.as_deref() == Some("local");

    // If running as beacon (and not forced local), serve aggregated coverage from all nodes
    if state.is_beacon && !force_local {
        let beacon_db_path = state.data_dir.join("beacon.db");
        if beacon_db_path.exists() {
            if let Ok(reg) = crate::beacon::BeaconRegistry::new(&beacon_db_path) {
                match reg.get_aggregated_coverage() {
                    Ok(coverage) => return (StatusCode::OK, Json(coverage)).into_response(),
                    Err(e) => eprintln!("⚠️  Beacon aggregated coverage failed: {}", e),
                }
            }
        }
    }

    // Serve pre-computed MGRS tile polygons (generated by Python with pyproj)
    let poly_path = state.data_dir.join("coverage_spatial.json");
    if poly_path.exists() {
        match std::fs::read_to_string(&poly_path) {
            Ok(json_str) => {
                match serde_json::from_str::<serde_json::Value>(&json_str) {
                    Ok(val) => return (StatusCode::OK, Json(val)).into_response(),
                    Err(_) => {}
                }
            }
            Err(_) => {}
        }
    }

    // Fallback: bbox-based coverage from DB
    let catalog = state.catalog.lock().await;
    let tiles = catalog.mgrs_coverage().unwrap_or_default();
    let mut collections: std::collections::HashMap<String, Vec<serde_json::Value>> =
        std::collections::HashMap::new();
    for t in &tiles {
        collections.entry(t.collection.clone()).or_default().push(
            serde_json::json!({
                "bbox": [t.west, t.south, t.east, t.north],
                "tile_id": t.tile_id,
                "date_count": t.date_count,
            })
        );
    }
    let col_map: serde_json::Value = collections
        .into_iter()
        .map(|(k, v)| (k, serde_json::json!({ "cells": v })))
        .collect();

    (StatusCode::OK, Json(serde_json::json!({
        "collections": col_map,
    }))).into_response()
}


pub(crate) async fn stats_coverage(State(state): State<AppState>) -> impl IntoResponse {
    let catalog = state.catalog.lock().await;
    let total = catalog.item_count(None).unwrap_or(0);
    let collections = catalog.list_collections().unwrap_or_default();
    let per_col: Vec<serde_json::Value> = collections
        .iter()
        .map(|c| {
            let count = catalog.item_count(Some(&c.id)).unwrap_or(0);
            serde_json::json!({ "collection": c.id, "item_count": count })
        })
        .collect();
    (StatusCode::OK, Json(serde_json::json!({
        "total_items": total,
        "collections": per_col,
    }))).into_response()
}


